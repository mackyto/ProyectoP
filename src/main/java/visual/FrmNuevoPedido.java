        private void cargarTablaArticulos(String filtro) {
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblArticulos.getModel();
            modelo.setRowCount(0);

            articulosMostrados = gestor.buscarArticulos(filtro);

            for (Articulo art : articulosMostrados) {
                String infoStock = "-";
                if (art instanceof ProductoFisico) {
                    ProductoFisico producto = (ProductoFisico) art;
                    infoStock = String.valueOf(producto.getStock());
                }
                modelo.addRow(new Object[]{infoStock, art.getNombre(), art.precioUnitario() + " €"});
            }
        }

        private void actualizarTablaLineasDerecha() throws ErrorDatos {
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblLineasDerecha.getModel();
            modelo.setRowCount(0); // Borramos todo antes de pintar para no duplicar filas visuales

            for (LineaPedido linea : pedidoEnCurso.getLista()) {
                int cant = linea.getCantidad();
                String nombre = linea.getArticulo().getNombre();
                double ivaPorcentaje = linea.getArticulo().getIva();
                double pUnitario = linea.getPrecioUnitarioFinal();
                double totalFila = pUnitario * cant;

                modelo.addRow(new Object[]{
                    cant,
                    nombre,
                    ivaPorcentaje + "%",
                    String.format("%.2f €", pUnitario),
                    String.format("%.2f €", totalFila)
                });
            }

            lblTotal.setText(String.format("Total Pedido: %.2f €", pedidoEnCurso.calcularTotal()));

        }

   


