    private void btnConfirmarPedidoEnCursoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarPedidoEnCursoActionPerformed
        if (pedidoEnCurso.getLista().isEmpty()) {
            JOptionPane.showMessageDialog(this, "No puedes guardar un pedido vacío.");
            return;
        }
        try {
            gestor.confirmarPedido();
        } catch (ErrorDatos ex) {
            System.getLogger(FrmNuevoPedido.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        JOptionPane.showMessageDialog(this, "¡Pedido guardado con éxito!");
        this.dispose();
    }//GEN-LAST:event_btnConfirmarPedidoEnCursoActionPerformed

    private void tblArticulosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblArticulosMouseClicked
        int fila = tblArticulos.getSelectedRow();
        if (fila != -1) {
            articuloSeleccionado = articulosMostrados.get(fila);
            txtNombreArticulo.setText(articuloSeleccionado.getNombre());
            txtCantidad.setText("1");
            txtCantidad.requestFocus();
        }
    }//GEN-LAST:event_tblArticulosMouseClicked

    private void btnConfimarLineaPedidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfimarLineaPedidoActionPerformed
        if (articuloSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Por favor, selecciona un artículo de la tabla primero.");
            return;
        }

        try {
            int cantidad = Integer.parseInt(txtCantidad.getText());
            if (cantidad <= 0) {
                throw new NumberFormatException();
            }
            gestor.anadirLineaPedido(articuloSeleccionado, cantidad);
            articuloSeleccionado = null;
            txtNombreArticulo.setText("");
            txtCantidad.setText("");
            actualizarTablaLineasDerecha();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser un número entero mayor que 0.");
        } catch (ErrorDatos ex) {
            System.getLogger(FrmNuevoPedido.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_btnConfimarLineaPedidoActionPerformed

