    private void actualizarTabla(String patron) {
        // Definimos las columnas
        String[] titulos = {"ID", "Nombre", "Apellidos", "Teléfono", "Email", "Fid."};
        DefaultTableModel modelo = new DefaultTableModel(titulos, 0);

        // Pedimos los objetos al gestor
        List<Cliente> lista = gestor.buscarClientes(patron);

        // Pasamos los objetos a filas de la tabla
        for (Cliente c : lista) {
            Object[] fila = {
                c.getId(),
                c.getNombre(),
                c.getApellidos(),
                c.getTelefono(),
                c.getEmail(),
                c.getNivelFidelidad()
            };
            modelo.addRow(fila);
        }
        tblCliente.setModel(modelo);
    }

