    private void txtPatronKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPatronKeyReleased
        String patron = txtPatron.getText();
        List<Cliente> result = gestor.buscarClientes(patron);

// 3. ¡CAMBIO CLAVE! Usamos DefaultTableModel en lugar de ListModel
        String[] titulos = {"ID", "Nombre", "Apellidos", "Teléfono", "Email"};
        DefaultTableModel modeloTabla = new DefaultTableModel(titulos, 0);

        // 4. Llenamos el modelo de la tabla fila por fila
        for (Cliente c : result) {
            Object[] fila = {
                c.getId(),
                c.getNombre(),
                c.getApellidos(),
                c.getTelefono(),
                c.getEmail()
            };
            modeloTabla.addRow(fila);
        }

        // 5. Se lo asignamos a la tabla (asegúrate de que el nombre sea tblClientes)
        tblCliente.setModel(modeloTabla);

    }//GEN-LAST:event_txtPatronKeyReleased

